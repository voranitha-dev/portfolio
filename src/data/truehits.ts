import rawData from './truehitsData.json';
import { NATION_BRAND_PLATFORMS, NationBrandPlatform } from './portfolioData';

export interface TruehitsDailyMetrics {
  rankThailand: number;
  rankAll: number;
  dailyUipThailand: number;
  dailyUipAll: number;
  thailandSharePct: number;
  dailyVisitorsThailand: number;
}

export interface TruehitsMonthlyMetrics {
  rank: number;
  avgDailyUip: number;
  avgDailySessions: number;
  avgDailyPageviews: number;
}

export interface TruehitsMonthlySnapshot {
  monthKey: string;
  monthLabel: string;
  shortLabel: string;
  daysInMonth: number;
  sourceUrl: string;
  brands: Record<string, TruehitsMonthlyMetrics>;
}

export interface TruehitsData {
  updatedAt: string | null;
  daily: { date: string | null; sourceUrl: string; brands: Record<string, TruehitsDailyMetrics> } | null;
  monthly: TruehitsMonthlySnapshot[];
}

/** Generated by scripts/fetchTruehits.mjs (refreshed on every scheduled deploy). */
export const TRUEHITS: TruehitsData = rawData as TruehitsData;

export const TRUEHITS_RANKING_URL = 'https://truehits.net/ranking/view.php';

export interface DailyBrandEntry {
  brand: NationBrandPlatform;
  metrics: TruehitsDailyMetrics;
}

/** Brands with a daily snapshot, sorted by unique IPs (desc). */
export const DAILY_BRAND_ENTRIES: DailyBrandEntry[] = NATION_BRAND_PLATFORMS.flatMap((brand) => {
  const metrics = TRUEHITS.daily?.brands[brand.id];
  return metrics ? [{ brand, metrics }] : [];
}).sort((a, b) => b.metrics.dailyUipAll - a.metrics.dailyUipAll);

export const NETWORK_DAILY = {
  date: TRUEHITS.daily?.date ?? null,
  totalUip: DAILY_BRAND_ENTRIES.reduce((sum, e) => sum + e.metrics.dailyUipAll, 0),
  totalUipThailand: DAILY_BRAND_ENTRIES.reduce((sum, e) => sum + e.metrics.dailyUipThailand, 0),
  totalVisitors: DAILY_BRAND_ENTRIES.reduce((sum, e) => sum + e.metrics.dailyVisitorsThailand, 0),
  top20Count: DAILY_BRAND_ENTRIES.filter((e) => e.metrics.rankThailand <= 20).length,
  top50Count: DAILY_BRAND_ENTRIES.filter((e) => e.metrics.rankThailand <= 50).length,
};

export const LATEST_MONTH = TRUEHITS.monthly[TRUEHITS.monthly.length - 1];

/** Total monthly pageviews for the whole network in a given snapshot. */
export const networkMonthlyPageviews = (snapshot: TruehitsMonthlySnapshot) =>
  Object.values(snapshot.brands).reduce((sum, b) => sum + b.avgDailyPageviews * snapshot.daysInMonth, 0);

const PREVIOUS_MONTH = TRUEHITS.monthly[TRUEHITS.monthly.length - 2];

export interface MonthlyBrandEntry {
  brand: NationBrandPlatform;
  /** Estimated monthly pageviews = average daily pageviews × days in month. */
  pageviews: number;
  rank: number;
}

/** Brands in the latest monthly report, sorted by estimated monthly pageviews (desc). */
export const MONTHLY_BRAND_ENTRIES: MonthlyBrandEntry[] = LATEST_MONTH
  ? NATION_BRAND_PLATFORMS.flatMap((brand) => {
      const rec = LATEST_MONTH.brands[brand.id];
      return rec ? [{ brand, pageviews: rec.avgDailyPageviews * LATEST_MONTH.daysInMonth, rank: rec.rank }] : [];
    }).sort((a, b) => b.pageviews - a.pageviews)
  : [];

const latestPageviews = LATEST_MONTH ? networkMonthlyPageviews(LATEST_MONTH) : 0;
const previousPageviews = PREVIOUS_MONTH ? networkMonthlyPageviews(PREVIOUS_MONTH) : 0;

export const MONTHLY_NETWORK = {
  pageviews: latestPageviews,
  /** % change vs the previous month, or null when there is no previous month. */
  changePct: previousPageviews ? ((latestPageviews - previousPageviews) / previousPageviews) * 100 : null,
  previousLabel: PREVIOUS_MONTH?.monthLabel ?? '',
  previousShortLabel: PREVIOUS_MONTH?.shortLabel ?? '',
  top25Count: MONTHLY_BRAND_ENTRIES.filter((e) => e.rank > 0 && e.rank <= 25).length,
};
